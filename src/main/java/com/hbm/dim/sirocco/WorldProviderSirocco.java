package com.hbm.dim.sirocco;

import java.util.Random;

import com.hbm.blocks.ModBlocks;
import com.hbm.dim.ChunkProviderCelestial;
import com.hbm.dim.WorldProviderCelestial;
import com.hbm.dim.duna.biome.BiomeGenBaseDuna;
import com.hbm.util.ParticleUtil;

import cpw.mods.fml.relauncher.Side;
import cpw.mods.fml.relauncher.SideOnly;
import net.minecraft.block.Block;
import net.minecraft.client.Minecraft;
import net.minecraft.entity.EntityLivingBase;
import net.minecraft.init.Blocks;
import net.minecraft.util.MathHelper;
import net.minecraft.world.World;
import net.minecraft.world.biome.BiomeGenBase;
import net.minecraft.world.biome.WorldChunkManagerHell;
import net.minecraft.world.chunk.IChunkProvider;
import net.minecraft.world.gen.NoiseGeneratorPerlin;

public final class WorldProviderSirocco extends WorldProviderCelestial {
    private static final long STORM_CYCLE = 96000;
    private static final long STORM_LENGTH = 12000;

    @Override public String getDimensionName() { return "Sirocco"; }
    @Override public Block getStone() { return ModBlocks.duna_rock; }

    @Override public void registerWorldChunkManager() {
        worldChunkMgr = new WorldChunkManagerHell(BiomeGenBaseDuna.dunaPlains, 0);
    }

    @Override public IChunkProvider createChunkGenerator() {
        return new Terrain(worldObj, worldObj.getSeed());
    }

    private float stormStrength() {
        long phase = Math.floorMod(getMasterWorldTime(), STORM_CYCLE);
        return MathHelper.clamp_float(Math.min(phase, STORM_LENGTH - phase) / 600F, 0F, 1F);
    }

    @Override public float fogDensity() {
        return Math.max(super.fogDensity(), stormStrength() * 0.045F);
    }

    @Override public void updateWeather() {
        super.updateWeather();
        if(worldObj.isRemote && stormStrength() > 0.1F) showDust();
    }

    @SideOnly(Side.CLIENT)
    private void showDust() {
        EntityLivingBase view = Minecraft.getMinecraft().renderViewEntity;
        if(view == null) return;
        Random random = worldObj.rand;
        double x = view.posX + random.nextDouble() * 56 - 28;
        double z = view.posZ + random.nextDouble() * 56 - 28;
        int y = MathHelper.floor_double(view.posY) + random.nextInt(7) - 3;
        if(worldObj.blockExists(MathHelper.floor_double(x), y, MathHelper.floor_double(z))
                && worldObj.canBlockSeeTheSky(MathHelper.floor_double(x), y, MathHelper.floor_double(z)))
            ParticleUtil.spawnDustFlame(worldObj, x, y, z, -2.5, 0, 0);
    }

    private static final class Terrain extends ChunkProviderCelestial {
        private final NoiseGeneratorPerlin relief;
        private final NoiseGeneratorPerlin wind;

        Terrain(World world, long seed) {
            super(world, seed, false);
            stoneBlock = ModBlocks.duna_rock;
            Random random = new Random(seed ^ 0x5349524F43434F4CL);
            relief = new NoiseGeneratorPerlin(random, 2);
            wind = new NoiseGeneratorPerlin(random, 2);
        }

        @Override protected void replaceBlocksForBiome(int chunkX, int chunkZ, Block[] blocks, byte[] metadata, BiomeGenBase[] biomes) {
            for(int z = 0; z < 16; z++) for(int x = 0; x < 16; x++) {
                int worldX = chunkX * 16 + x, worldZ = chunkZ * 16 + z;
                int column = (z * 16 + x) * 256;
                int top = 200;
                while(top > 10 && blocks[column + top] != stoneBlock) top--;

                double region = relief.func_151601_a(worldX / 320D, worldZ / 320D);
                double detail = wind.func_151601_a(worldX / 38D, worldZ / 66D);
                boolean plateau = region > 0.55;
                double dune = (1 + Math.sin((worldX + worldZ * 0.35) / 13 + detail)) * 0.5;
                int rise = plateau ? (int)(Math.min(1, (region - 0.55) * 6) * 27)
                        : (int)(dune * MathHelper.clamp_double((region + 0.65) * 15, 1, 15));
                int surface = top + rise;
                for(int y = top + 1; y <= surface; y++) blocks[column + y] = stoneBlock;
                if(!plateau) {
                    int depth = 4 + rise;
                    for(int y = surface; y > surface - depth; y--) blocks[column + y] = ModBlocks.duna_sands;
                }
                if(detail > 0.15) {
                    int bottom = 16 + (int)(Math.min(detail, 2) * 6);
                    for(int y = bottom; y < bottom + 7; y++)
                        if(blocks[column + y] == stoneBlock) blocks[column + y] = ModBlocks.duna_sands;
                }
                for(int y = rand.nextInt(4); y >= 0; y--) blocks[column + y] = Blocks.bedrock;
            }
        }

        @Override public void populate(IChunkProvider provider, int x, int z) {
            // All surface features are generated by the single-chunk expedition generator.
        }
    }
}
